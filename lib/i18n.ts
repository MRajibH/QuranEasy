import type { Locale } from "./types";

export const LOCALES: Locale[] = ["bn", "en"];
export const DEFAULT_LOCALE: Locale = "bn";
export const isLocale = (x: string): x is Locale => (LOCALES as string[]).includes(x);

const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
export const toBnDigits = (s: string | number) => String(s).replace(/\d/g, (d) => BN_DIGITS[Number(d)]);

/** Locale-aware number: Bangla digits in the Bangla UI. */
export function num(locale: Locale, n: number | string, opts?: Intl.NumberFormatOptions) {
  const s = typeof n === "number" ? new Intl.NumberFormat("en-US", opts).format(n) : n;
  return locale === "bn" ? toBnDigits(s) : s;
}

